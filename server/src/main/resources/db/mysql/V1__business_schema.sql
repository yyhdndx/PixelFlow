CREATE TABLE users (
 id VARCHAR(36) PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, nickname VARCHAR(40) NOT NULL,
 role VARCHAR(16) NOT NULL CHECK (role IN ('CREATOR','ADMIN')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE sessions (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL,
 refresh_hash VARCHAR(64) NOT NULL UNIQUE, expires_at BIGINT NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE posts (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 author_id VARCHAR(36) NOT NULL, title VARCHAR(120) NOT NULL,
 content VARCHAR(5000) NOT NULL, clips_json TEXT NOT NULL,
 has_video BOOLEAN NOT NULL, status VARCHAR(16) NOT NULL
 CHECK (status IN ('DRAFT','PENDING','PUBLISHED','REJECTED','WITHDRAWN')),
 create_time BIGINT NOT NULL,
 FOREIGN KEY (author_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE INDEX posts_feed ON posts(status, id);
CREATE TABLE interactions (
 user_id VARCHAR(36) NOT NULL, kind VARCHAR(24) NOT NULL,
 target_id VARCHAR(36) NOT NULL, PRIMARY KEY (user_id,kind,target_id),
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE behavior_events (
 seq BIGINT AUTO_INCREMENT PRIMARY KEY,
 event_id VARCHAR(64) NOT NULL, user_id VARCHAR(36) NOT NULL,
 post_id BIGINT NOT NULL, event_type VARCHAR(24) NOT NULL,
 occurred_at BIGINT NOT NULL, received_at BIGINT NOT NULL,
 UNIQUE(user_id,event_id),
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (post_id) REFERENCES posts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE moderation_records (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 actor_id VARCHAR(36) NOT NULL, post_id BIGINT NOT NULL,
 before_status VARCHAR(16) NOT NULL, after_status VARCHAR(16) NOT NULL,
 reason VARCHAR(500) NOT NULL, created_at BIGINT NOT NULL,
 FOREIGN KEY (actor_id) REFERENCES users(id),
 FOREIGN KEY (post_id) REFERENCES posts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
