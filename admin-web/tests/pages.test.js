import { beforeEach, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import Moderation from '../src/pages/moderation/Moderation.vue'
import Users from '../src/pages/users/Users.vue'
import { request, write } from '../src/api/client'
vi.mock('../src/api/client', () => ({ request: vi.fn(), write: vi.fn(), session: { user: { id: 'admin' } } }))
const post = { post_id: '100', title: '中文作品', content: '正文', author: { nickname: '作者A' }, clips: [], submit_time: 1700000000 }
beforeEach(() => vi.resetAllMocks())
it('shows pending-queue submit time and waiting duration, with a dash when unknown', async () => {
  const withTime = { ...post, submit_time: Math.floor(Date.now() / 1000) - 7200 }
  const withoutTime = { ...post, post_id: '101', submit_time: null }
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [withTime, withoutTime] : [])
  const wrapper = mount(Moderation)
  await flushPromises()
  expect(wrapper.text()).toContain('等待 2 小时')
  expect(wrapper.text()).toMatch(/提交时间 \d{4}\/\d{1,2}\/\d{1,2}/)
  expect(wrapper.text()).toContain('提交时间 —')
  wrapper.unmount()
})
it('sends a decision and displays persisted audit data', async () => {
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [post] : [])
  write.mockResolvedValue({ postId: '100', status: 'PUBLISHED' })
  const wrapper = mount(Moderation)
  await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '查看并审核').trigger('click')
  await wrapper.find('textarea').setValue('内容符合规范')
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [] : [{ id: 1, post_id: 100, actor_id: 'admin', before_status: 'PENDING', after_status: 'PUBLISHED', reason: '内容符合规范', created_at: 1 }])
  await wrapper.findAll('button').find(b => b.text() === '通过').trigger('click')
  await flushPromises()
  expect(write).toHaveBeenCalledWith('/api/admin/posts/100/moderation', 'POST', { status: 'PUBLISHED', reason: '内容符合规范' })
  expect(wrapper.text()).toContain('待审核 → 已通过')
  expect(wrapper.find('[role="status"]').text()).toContain('已通过')
  wrapper.unmount()
})
it('does not report a failed moderation as successful', async () => {
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [post] : [])
  write.mockRejectedValue(new Error('审核失败'))
  const wrapper = mount(Moderation)
  await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '查看并审核').trigger('click')
  await wrapper.find('textarea').setValue('请修改')
  await wrapper.findAll('button').find(b => b.text() === '驳回').trigger('click')
  await flushPromises()
  expect(wrapper.find('[role="alert"]').text()).toBe('审核失败')
  expect(wrapper.find('[role="status"]').exists()).toBe(false)
  wrapper.unmount()
})
it('reads past 50 historical records and prepends new decisions without duplicating history', async () => {
  const record = id => ({ id, post_id: id, actor_id: 'admin', before_status: 'PENDING', after_status: 'PUBLISHED', reason: `审核理由 ${id}`, created_at: id })
  request.mockImplementation(async path => {
    if (path.startsWith('/api/admin/posts')) return [post]
    const after = Number(new URL(path, 'http://localhost').searchParams.get('after'))
    return after === 0 ? Array.from({ length: 50 }, (_, index) => record(index + 1)) : after === 50 ? [record(51)] : []
  })
  const wrapper = mount(Moderation)
  await flushPromises()
  expect(request).toHaveBeenCalledWith('/api/admin/moderation?count=50&after=50')
  expect(wrapper.find('tbody tr').text()).toContain('审核理由 51')
  await wrapper.findAll('button').find(b => b.text() === '查看并审核').trigger('click')
  await wrapper.find('textarea').setValue('最新审核')
  write.mockResolvedValue({ postId: '100', status: 'PUBLISHED' })
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [] : [record(52)])
  await wrapper.findAll('button').find(b => b.text() === '通过').trigger('click')
  await flushPromises()
  expect(request).toHaveBeenCalledWith('/api/admin/moderation?count=50&after=51')
  expect(wrapper.find('tbody tr').text()).toContain('审核理由 52')
  expect(wrapper.findAll('tbody tr')).toHaveLength(52)
  wrapper.unmount()
})
it('preserves a 409 error after refreshing and closes the stale review', async () => {
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [post] : [])
  write.mockRejectedValue(Object.assign(new Error('作品已被其他管理员处理'), { status: 409 }))
  const wrapper = mount(Moderation)
  await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '查看并审核').trigger('click')
  await wrapper.find('textarea').setValue('通过')
  request.mockResolvedValue([])
  await wrapper.findAll('button').find(b => b.text() === '通过').trigger('click')
  await flushPromises()
  expect(wrapper.find('[role="alert"]').text()).toBe('作品已被其他管理员处理')
  expect(wrapper.find('[aria-label="审核作品"]').exists()).toBe(false)
  expect(wrapper.text()).toContain('暂无待审核作品')
  expect(wrapper.find('[role="status"]').exists()).toBe(false)
  wrapper.unmount()
})
it('requires a reason for user changes and renders the server result', async () => {
  request.mockResolvedValue([{ id: 'user-a', username: 'alice', nickname: '作者', enabled: true, role: 'CREATOR' }, { id: 'admin', username: 'admin', enabled: true, role: 'ADMIN' }])
  write.mockResolvedValue({ id: 'user-a', enabled: false })
  const wrapper = mount(Users)
  await flushPromises()
  expect(wrapper.findAll('button').find(b => b.text() === '当前账号').attributes('disabled')).toBeDefined()
  await wrapper.findAll('button').find(b => b.text() === '禁用').trigger('click')
  expect(wrapper.find('form button').attributes('disabled')).toBeDefined()
  await wrapper.find('textarea').setValue('违反社区规则')
  await wrapper.find('form').trigger('submit')
  await flushPromises()
  expect(write).toHaveBeenCalledWith('/api/admin/users/user-a/status', 'PUT', { enabled: false, reason: '违反社区规则' })
  expect(wrapper.find('[role="status"]').text()).toContain('账号已禁用')
  expect(wrapper.text()).toContain('已禁用')
  wrapper.unmount()
})
it('loads an AI suggestion automatically on open and prefills the moderation reason', async () => {
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [post] : [])
  write.mockResolvedValue({ status_code: 0, suggestion: {
    suggestion_id: 's-1', post_id: '100', risk_level: 'high', recommended_action: 'reject',
    reason: '命中违禁词规则，建议驳回', rule_hits: ['banned_word'], suggestions: [],
    policy_version: 'content-safety-v1', provider: 'rules', latency_ms: 5, trace_id: 't-1', degraded: 1 } })
  const wrapper = mount(Moderation)
  await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '查看并审核').trigger('click')
  await flushPromises()
  expect(write).toHaveBeenCalledWith('/api/admin/agent/moderation-suggestion', 'POST', { post_id: '100' })
  expect(wrapper.text()).toContain('高风险')
  expect(wrapper.text()).toContain('建议驳回')
  expect(wrapper.text()).toContain('命中违禁词规则，建议驳回')
  await wrapper.findAll('button').find(b => b.text() === '将理由填入审核理由').trigger('click')
  expect(wrapper.find('textarea').element.value).toBe('命中违禁词规则，建议驳回')
  wrapper.unmount()
})
it('surfaces suggestion failures without touching the review state', async () => {
  request.mockImplementation(async path => path.startsWith('/api/admin/posts') ? [post] : [])
  write.mockRejectedValue(new Error('建议服务暂时不可用'))
  const wrapper = mount(Moderation)
  await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '查看并审核').trigger('click')
  await flushPromises()
  expect(write).toHaveBeenCalledWith('/api/admin/agent/moderation-suggestion', 'POST', { post_id: '100' })
  expect(wrapper.find('[role="alert"]').text()).toBe('建议服务暂时不可用')
  expect(wrapper.find('textarea').exists()).toBe(true)
  wrapper.unmount()
})
